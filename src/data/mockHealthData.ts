export function computeBiomarkerStatus(
  value: number,
  lo: number,
  hi: number
): BiomarkerStatus {
  if (value >= lo && value <= hi) return 'optimal';
  const span = Math.max(hi - lo, 1);
  const tolerance = span * 0.12;
  if ((value < lo && lo - value <= tolerance) || (value > hi && value - hi <= tolerance)) {
    return 'borderline';
  }
  return 'out';
}

export function getStatusPillLabel(m: Pick<Biomarker, 'status' | 'value' | 'hi' | 'lo'>): string {
  if (m.status === 'optimal') return 'Ideal';
  if (m.status === 'borderline') return 'Atenção';
  return m.value > m.hi ? 'Alto' : 'Baixo';
}

